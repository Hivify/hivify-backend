using Association.Application.Contracts;
using Identity.Domain;
using Microsoft.AspNetCore.Identity;
using Microsoft.Extensions.Options;
using System.Security.Claims;

namespace Identity.Infrastructure.DotNETIdentity;

public sealed class HivifyClaimsPrincipalFactory(
    UserManager<DotNETApplicationUser> userManager,
    RoleManager<IdentityRole<Guid>> roleManager,
    IOptions<IdentityOptions> options,
    ITenantClaimsService tenantClaimsService)
    : UserClaimsPrincipalFactory<
        DotNETApplicationUser,
        IdentityRole<Guid>>(
            userManager,
            roleManager,
            options)
{
    protected override async Task<ClaimsIdentity> GenerateClaimsAsync(
        DotNETApplicationUser user)
    {
        // Preserve all the normal claims generated by Identity.
        var identity = await base.GenerateClaimsAsync(user);

        // Add claims for this user's saved tenant memberships.
        var tenantClaims =
            await tenantClaimsService.GetClaimsAsync(user.Id);

        foreach (var claim in tenantClaims)
        {
            identity.AddClaim(claim);
        }

        return identity;
    }
}